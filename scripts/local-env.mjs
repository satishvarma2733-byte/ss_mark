// Writes git-ignored .env.local files from the running LOCAL Supabase stack (`supabase status`).
// Local CLI keys only. Never point this at a hosted project. Usage: pnpm env:local
import { execSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const bin = join(root, "node_modules", ".bin", process.platform === "win32" ? "supabase.cmd" : "supabase");
// Fixed command string (no user input); a shell is needed to run the .cmd shim on Windows.
const raw = execSync(`"${bin}" status -o json`, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
const status = JSON.parse(raw.slice(raw.indexOf("{")));

const required = ["API_URL", "DB_URL", "PUBLISHABLE_KEY"];
for (const key of required) {
  if (!status[key]) throw new Error(`supabase status did not report ${key}; is the local stack running?`);
}
for (const key of ["API_URL", "DB_URL"]) {
  const host = new URL(status[key]).hostname;
  if (host !== "127.0.0.1" && host !== "localhost") throw new Error(`Refusing to write non-local ${key}`);
}

// Local-only server secrets (mock gateway, arrival codes). Generated once and then reused, because rotating them would
// invalidate webhook signatures between web and worker and the arrival codes of existing local bookings.
function existingValue(file, name) {
  const path = join(root, file);
  if (!existsSync(path)) return undefined;
  const line = readFileSync(path, "utf8").split(/\r?\n/).find((l) => l.startsWith(`${name}=`));
  return line ? line.slice(name.length + 1) : undefined;
}
const keep = (name, make) => existingValue("apps/web/.env.local", name) ?? existingValue(".env.local", name) ?? make();
const secrets = {
  MOCK_GATEWAY_ENABLED: "true",
  MOCK_GATEWAY_KEY_ID: keep("MOCK_GATEWAY_KEY_ID", () => `mock_key_${randomBytes(8).toString("hex")}`),
  MOCK_GATEWAY_KEY_SECRET: keep("MOCK_GATEWAY_KEY_SECRET", () => randomBytes(32).toString("base64url")),
  MOCK_GATEWAY_WEBHOOK_SECRET: keep("MOCK_GATEWAY_WEBHOOK_SECRET", () => randomBytes(32).toString("base64url")),
  ARRIVAL_CODE_SECRET: keep("ARRIVAL_CODE_SECRET", () => randomBytes(32).toString("base64url"))
};

// The emulator reaches the host through `adb reverse`, so the same localhost URLs work on Android.
const api = status.API_URL.replace("127.0.0.1", "localhost");
const header = "# Generated by scripts/local-env.mjs from the LOCAL Supabase stack. Git-ignored. Do not commit.\n";
const files = {
  ".env.local": {
    DATABASE_URL: status.DB_URL,
    SUPABASE_URL: api,
    SUPABASE_PUBLISHABLE_KEY: status.PUBLISHABLE_KEY,
    MAILPIT_URL: status.MAILPIT_URL ?? status.INBUCKET_URL ?? "",
    APP_URL: "http://localhost:3000",
    NEXT_PUBLIC_APP_URL: "http://localhost:3000",
    ...secrets
  },
  "apps/web/.env.local": {
    APP_ENV: "development",
    APP_MODE: "mock",
    DATABASE_URL: status.DB_URL,
    NEXT_PUBLIC_APP_URL: "http://localhost:3000",
    NEXT_PUBLIC_SUPABASE_URL: api,
    NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: status.PUBLISHABLE_KEY,
    ...secrets
  },
  "apps/worker/.env.local": {
    APP_ENV: "development",
    APP_MODE: "mock",
    DATABASE_URL: status.DB_URL,
    NEXT_PUBLIC_APP_URL: "http://localhost:3000",
    ...secrets
  },
  "apps/mobile/.env.local": {
    EXPO_PUBLIC_API_URL: "http://localhost:3000",
    EXPO_PUBLIC_SUPABASE_URL: api,
    EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY: status.PUBLISHABLE_KEY
  }
};

for (const [file, values] of Object.entries(files)) {
  const body = header + Object.entries(values).map(([k, v]) => `${k}=${v}`).join("\n") + "\n";
  writeFileSync(join(root, file), body, { encoding: "utf8" });
  console.info(`wrote ${file} (${Object.keys(values).join(", ")})`); // names only, never values
}
